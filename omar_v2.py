"""TAURUS Omar v2: closed-bar 1H uptrend + 5M breakout, volume and retest.

Research implementation. Requires two CONFIRMED rising 1H pivot lows and
higher highs, 5M resistance known before breakout, breakout >=1.5x 20-bar
median volume, then a confirmed retest within six 5M bars. Long only.
"""
from datetime import datetime,timezone
from zoneinfo import ZoneInfo
from statistics import median

NY=ZoneInfo('America/New_York')
KEY='omar_v2_volume_retest'
MIN_VOLUME_RATIO=1.5
LOOKBACK=20
RETEST_WINDOW=6
TICK={'nq':.25,'mes':.25,'mgc':.10}

def _hours(bars):
    """Only completed 1H buckets (12 consecutive 5M bars)."""
    grouped={}
    for b in bars:
        k=(int(b['time'])//3600)*3600
        grouped.setdefault(k,[]).append(b)
    out=[]
    for t,rows in sorted(grouped.items()):
        rows=sorted(rows,key=lambda b:b['time'])
        if len(rows)!=12 or [int(b['time']) for b in rows]!=[t+i*300 for i in range(12)]:
            continue
        out.append({'time':t,'high':max(float(b['high']) for b in rows),
                    'low':min(float(b['low']) for b in rows),
                    'close':float(rows[-1]['close'])})
    return out

def _pivots(hours):
    """Confirmed with 2 candles on the right: no future pivots at signal."""
    highs=[];lows=[]
    for i in range(2,len(hours)-2):
        h=hours[i]
        if all(h['high']>hours[j]['high'] for j in (i-2,i-1,i+1,i+2)):
            highs.append(h['high'])
        if all(h['low']<hours[j]['low'] for j in (i-2,i-1,i+1,i+2)):
            lows.append(h['low'])
    return highs,lows

def _uptrend(bars):
    hours=_hours(bars)
    if len(hours)<10:return False
    highs,lows=_pivots(hours)
    return len(highs)>=2 and len(lows)>=2 and highs[-1]>highs[-2] and lows[-1]>lows[-2]

def _levels(bars,i):
    """5M resistance levels from prior closed bars, never the signal bar."""
    if i<LOOKBACK+6:return []
    # A prior pivot high is known only after two right-side completed bars.
    lo=max(2,i-45)
    levels=[]
    for j in range(lo,i-2):
        h=float(bars[j]['high'])
        if h>=max(float(bars[k]['high']) for k in (j-2,j-1,j+1,j+2)):
            levels.append(h)
    # Also include recent 20-bar range high (known prior to breakout).
    levels.append(max(float(b['high']) for b in bars[i-LOOKBACK:i]))
    return sorted(set(levels))

def signals(bars,market='nq'):
    if market not in TICK or len(bars)<150:return []
    out=[];used=set()
    for i in range(max(145,len(bars)-35),len(bars)):
        b=bars[i];prev=bars[i-1]
        # At time i the current 1H candle is not closed until its last 5M bar.
        # Only completed hours in the prefix can influence the trend.
        if not _uptrend(bars[max(0,i-360):i+1]):continue
        prior_vol=[float(x.get('volume') or 0) for x in bars[i-20:i]]
        if any(v<=0 for v in prior_vol):continue
        base=median(prior_vol)
        if base<=0 or float(b.get('volume') or 0)<MIN_VOLUME_RATIO*base:continue
        level_candidates=[l for l in _levels(bars,i)
                          if float(prev['close'])<=l<float(b['close'])]
        if not level_candidates:continue
        level=max(level_candidates)
        breakout_close=float(b['close'])
        # The RETEST is on a LATER closed bar; allow slight dip through level.
        tolerance=max(TICK[market]*2,(float(b['high'])-float(b['low']))*.2)
        for j in range(i+1,min(len(bars),i+RETEST_WINDOW+1)):
            x=bars[j]
            if int(x['time'])-int(b['time'])!=(j-i)*300:break
            if float(x['close'])<level-tolerance:break
            if float(x['low'])<=level+tolerance and float(x['close'])>level and float(x['close'])>float(x['open']):
                if not _uptrend(bars[max(0,j-360):j+1]):break
                stop=min(float(z['low']) for z in bars[i:j+1])-TICK[market]
                entry=float(x['close'])
                if stop>=entry:break
                # Never re-use same breakout/retest across repeated evaluations.
                key=(int(b['time']),int(x['time']),round(level,4))
                if key in used:break
                used.add(key)
                risk=entry-stop
                out.append(dict(id=f'{KEY}-{int(x["time"])}-{int(b["time"])}',
                  strategy=KEY,time=int(x['time']),side='LONG',
                  entry=round(entry,4),stop=round(stop,4),tp=round(entry+2*risk,4),
                  level=round(level,4),breakout_time=int(b['time']),timeframe='5m',
                  mnq_contracts=None,status='HISTORISCHES TESTSIGNAL',
                  reason=f'1H HH/HL, 5M Breakout >= {MIN_VOLUME_RATIO}x Medianvolumen, Retest innerhalb 6 Kerzen; 2R'))
                break
    # Same signal can be generated by overlapping historical candidates: keep one per
    # signal candle, favour most recent breakout.
    by_time={}
    for s in out:by_time[s['time']]=s
    return sorted(by_time.values(),key=lambda s:s['time'])

def build(bars,market='nq'):
    sig=signals(bars,market)
    recent=bool(sig and sig[-1]['time']==bars[-1]['time'])
    return dict(id=KEY,name='Omar V2 · Volumen-Retest (5M)',
       state='green' if recent else 'neutral',
       details='1H HH/HL + bestätigter 5M-Levelausbruch (Volumen ≥1,5× Median) + Retest; Long; nächster 5M-Open; SL unter Retest, 2R.',
       signals=sig[::-1],checks=[('1H HH/HL','green' if _uptrend(bars) else 'neutral'),
       ('Bestätigter Retest','green' if recent else 'neutral')])
